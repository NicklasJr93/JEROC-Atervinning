import { randomUUID } from 'node:crypto';
import { expect, test, type Page } from '@playwright/test';
import type { ArticleGroup } from '../src/catalog-types';
import type { PriceArticle, PricingState } from '../src/office/pricing-client';

test.use({ viewport: { width: 1440, height: 1000 }, isMobile: false, hasTouch: false });
const admin = { 'X-Demo-Actor': 'admin', 'X-Demo-User': 'admin' };
async function enterOffice(page: Page) {
  await page.goto('/kontor');
  await page.getByRole('button', { name: /Systemadmin/ }).click();
  await expect(page.locator('.office-main')).toHaveAttribute('aria-busy', 'false');
  await page.goto('/kontor#/prices');
  await expect(page.getByRole('heading', { name: 'Artiklar & priser', exact: true })).toBeVisible();
}

test('office creates groups and subgroups, links an article, uploads and orders its mobile images', async ({ page, request }) => {
  const suffix = randomUUID().slice(0, 8);
  const rootName = `UI grupp ${suffix}`;
  const childName = `UI undergrupp ${suffix}`;
  const articleName = `UI material ${suffix}`;
  await enterOffice(page);
  await page.getByRole('button', { name: 'Artikelgrupper', exact: true }).click();
  await page.getByRole('button', { name: 'Ny artikelgrupp', exact: true }).click();
  await expect(page.locator('nav[aria-label="Prisvyer"]')).toHaveCount(0);
  await page.getByLabel('Gruppnamn', { exact: true }).fill(rootName);
  await page.getByLabel('Beskrivning i appen', { exact: true }).fill('Gruppens instruktion från kontoret');
  await page.getByRole('button', { name: 'Välj referensbilder (0)', exact: true }).click();
  await page.getByRole('button', { name: 'Referensbild 1', exact: true }).click();
  await page.getByRole('button', { name: 'Spara artikelgrupp', exact: true }).click();
  await page.getByRole('button', { name: `Öppna artikelgrupp ${rootName}`, exact: true }).click();
  await page.getByRole('button', { name: 'Ny undergrupp', exact: true }).click();
  await page.getByLabel('Gruppnamn', { exact: true }).fill(childName);
  await page.getByRole('button', { name: 'Spara artikelgrupp', exact: true }).click();
  const initial = await (await request.get('/api/pricing/state', { headers: admin })).json() as PricingState;
  const root = initial.groups!.find(item => item.name === rootName)!;
  const child = initial.groups!.find(item => item.name === childName)!;
  expect(child.parentId).toBe(root.id);
  expect(root.photo).toBe(0);

  await page.getByRole('navigation', { name: 'Prisvyer', exact: true }).getByRole('button', { name: 'Artiklar & priser', exact: true }).click();
  await page.getByRole('button', { name: 'Ny artikel', exact: true }).click();
  await page.getByLabel('Artikelnamn', { exact: true }).fill(articleName);
  await page.getByLabel('Artikelgrupp', { exact: true }).selectOption(root.id);
  await page.getByLabel('Undergrupp', { exact: true }).selectOption(child.id);
  await page.getByLabel('Kort beskrivning', { exact: true }).fill('Samma text i kontoret och appen');
  await page.getByLabel('Exempel på vad som ingår', { exact: true }).fill('Ren koppar');
  await page.getByRole('button', { name: 'Välj referensbilder (0)', exact: true }).click();
  await page.getByRole('button', { name: 'Referensbild 2', exact: true }).click();
  await page.getByLabel('Ladda upp egna referensbilder', { exact: true }).setInputFiles('public/images/jeroc-logo.png');
  await expect(page.getByRole('button', { name: 'Spara artikel', exact: true })).toBeEnabled();
  await expect(page.locator('.office-article-images-selected li')).toHaveCount(2);
  await page.getByRole('button', { name: 'Gör bild 2 till huvudbild', exact: true }).click();
  const firstPreview = page.locator('.office-catalog-preview-gallery img').first();
  await expect(firstPreview).toHaveAttribute('src', /\/api\/article-media\/.+variant=thumb/);
  await expect(page.locator('.office-catalog-preview')).toContainText(rootName);
  await expect(page.locator('.office-catalog-preview')).toContainText(childName);
  await expect(page.locator('.office-catalog-preview')).toContainText('Ren koppar');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '/tmp/jeroc-catalog-editor.png', fullPage: true });
  await page.getByRole('button', { name: 'Spara artikel', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Artiklar & priser', exact: true })).toBeVisible();
  const saved = await (await request.get('/api/pricing/state', { headers: admin })).json() as PricingState;
  const article = saved.articles.find(item => item.name === articleName)!;
  expect(article.category).toBe(child.id);
  expect(article.photos[1]).toBe(1);
  expect(typeof article.photos[0]).toBe('string');
  const image = await request.get(`/api/article-media/${article.photos[0]}?variant=thumb`);
  expect(image.ok()).toBeTruthy();
  expect(image.headers()['content-type']).toContain('image/webp');
  const mobile = await (await request.get('/api/application/mobile', { headers: { 'X-Demo-Mobile': 'niklas' } })).json() as { catalog: PriceArticle[]; groups: ArticleGroup[] };
  expect(mobile.catalog.find(item => item.id === article.id)?.photos).toEqual(article.photos);
  expect(mobile.groups.find(item => item.id === child.id)?.parentId).toBe(root.id);
  await page.getByRole('button', { name: 'Artikelgrupper', exact: true }).click();
  await page.getByRole('button', { name: `Öppna artikelgrupp ${rootName}`, exact: true }).click();
  await expect(page.getByRole('table')).toContainText(articleName);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '/tmp/jeroc-catalog-group.png', fullPage: true });
});

test('article list scroll leaves heading, tabs, filters and table headings fixed; detail has breadcrumbs and back', async ({ page, request }) => {
  const actual = await (await request.get('/api/pricing/state', { headers: admin })).json() as PricingState;
  const fixture = { ...actual, articles: Array.from({ length: 75 }, (_, index) => ({ ...actual.articles[0], id: `scroll-${index}`, name: `Material ${index}` })) };
  await page.route('**/api/pricing/state', route => route.fulfill({ json: fixture }));
  await enterOffice(page);
  const heading = page.getByRole('heading', { name: 'Artiklar & priser', exact: true });
  const search = page.getByLabel('Sök artikel', { exact: true });
  const tabs = page.locator('nav[aria-label="Prisvyer"]');
  const head = page.locator('.office-pricing-article-panel th').first();
  const before = await Promise.all([heading.boundingBox(), search.boundingBox(), tabs.boundingBox(), head.boundingBox()]);
  await page.locator('.office-pricing-article-panel .office-pricing-table-wrap').evaluate(node => { node.scrollTop = 900; });
  await expect.poll(() => page.locator('.office-pricing-article-panel .office-pricing-table-wrap').evaluate(node => node.scrollTop)).toBeGreaterThan(500);
  const after = await Promise.all([heading.boundingBox(), search.boundingBox(), tabs.boundingBox(), head.boundingBox()]);
  before.forEach((box, index) => expect(Math.abs(box!.y - after[index]!.y)).toBeLessThan(2));
  await page.locator('.office-pricing-article-panel .office-pricing-table-wrap').evaluate(node => { node.scrollTop = 0; });
  await page.getByRole('button', { name: 'Redigera Material 0', exact: true }).click();
  await expect(tabs).toHaveCount(0);
  await expect(page.locator('nav[aria-label="Artikelns sökväg"]')).toContainText('Material 0');
  await page.getByRole('button', { name: 'Till artikelöversikten', exact: true }).click();
  await expect(tabs).toBeVisible();
  await expect(search).toBeVisible();
  await expect(page.locator('.office-sidebar nav').getByRole('button', { name: 'LME Cash', exact: true })).toHaveCount(0);
  await expect(tabs.getByRole('button', { name: 'LME Cash', exact: true })).toBeVisible();
});
